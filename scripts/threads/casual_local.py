def iter_pairs(theme: str) -> Iterable[Tuple[str, str]]:
    situations, reactions = _BANKS[theme]
    return itertools.product(situations, reactions)


def pair_count(theme: str) -> int:
    situations, reactions = _BANKS[theme]
    return len(situations) * len(reactions)


def format_post(situation: str, reaction: str) -> str:
    return f"{situation}\n{reaction}"


def generate_local_texts(
    count: int,
    *,
    avoid_keys: Set[str],
    text_key_fn,
    seed: int | None = None,
) -> List[Tuple[str, str]]:
    """Return list of (theme, text). Skips keys in avoid_keys."""
    rng = random.Random(seed)
    # Build shuffled candidate list per theme for fairness
    candidates: List[Tuple[str, str]] = []
    for theme in THEMES:
        pairs = [(theme, format_post(s, r)) for s, r in iter_pairs(theme)]
        rng.shuffle(pairs)
        candidates.extend(pairs)
    rng.shuffle(candidates)

    out: List[Tuple[str, str]] = []
    # Keep theme balance: round-robin among themes while scanning
    per_theme_need = {t: 0 for t in THEMES}
    base, rem = divmod(count, len(THEMES))
    for i, t in enumerate(THEMES):
        per_theme_need[t] = base + (1 if i < rem else 0)

    buckets: Dict[str, List[str]] = {t: [] for t in THEMES}
    for theme, text in candidates:
        if len(out) >= count:
            break
        if per_theme_need[theme] <= 0:
            continue
        key = text_key_fn(text)
        if key in avoid_keys:
            continue
        buckets[theme].append(text)
        avoid_keys.add(key)
        per_theme_need[theme] -= 1
        out.append((theme, text))

    # If some themes starved, fill remaining from any leftover candidates
    if len(out) < count:
        for theme, text in candidates:
            if len(out) >= count:
                break
            key = text_key_fn(text)
            if key in avoid_keys:
                continue
            avoid_keys.add(key)
            out.append((theme, text))

    return out[:count]
